#!/usr/bin/env python3
"""
Post (or update) the sticky Codex-Gravity review comment on a pull request.

Usage (inside a GitHub Action):
    python scripts/action_comment.py review.json

Environment: GITHUB_TOKEN, GITHUB_REPOSITORY, GITHUB_EVENT_PATH (or GITHUB_PR_NUMBER),
GITHUB_API_URL (optional).
"""

from __future__ import annotations

import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any, Callable, Optional

MARKER = "<!-- codex-gravity-review -->"

STATUS_BADGES = {
    "approved": "✅ **approved**",
    "changes_requested": "🛑 **changes requested**",
    "failed": "❌ **verification failed**",
    "unavailable": "⚠️ **no reviewer available**",
}

VERDICT_ICONS = {
    "approve": "✅",
    "revise": "🛑",
    "reject": "⛔",
    "abstain": "➖",
    "unavailable": "⚠️",
}


def _clip(text: str, limit: int = 400) -> str:
    text = (text or "").strip()
    return text if len(text) <= limit else text[: limit - 1] + "…"


def build_comment(result: dict[str, Any]) -> str:
    """Render a review result as one Markdown comment (pure, unit tested)."""
    status = str(result.get("status", "unknown"))
    decision = result.get("decision") or {}
    findings = result.get("findings") or []
    verification = result.get("verification") or {}

    lines = [
        MARKER,
        f"## {STATUS_BADGES.get(status, status)}",
        "",
        f"**{result.get('title', 'Change review')}** · {decision.get('reason', '')}",
        "",
    ]

    if findings:
        lines += ["| reviewer | verdict | summary |", "| --- | --- | --- |"]
        for finding in findings:
            verdict = str(finding.get("verdict", ""))
            icon = VERDICT_ICONS.get(verdict, "•")
            summary = _clip(finding.get("summary") or finding.get("error") or "", 160).replace("|", "\\|")
            lines.append(f"| `{finding.get('reviewer', '?')}` | {icon} {verdict or '—'} | {summary or '—'} |")
        lines.append("")

    blockers = decision.get("blockers") or []
    if blockers:
        lines.append("### Blocking issues")
        for item in blockers[:15]:
            lines.append(f"- {_clip(item, 500)}")
        if len(blockers) > 15:
            lines.append(f"- … and {len(blockers) - 15} more (see the transcript)")
        lines.append("")

    if verification:
        mark = "PASS" if verification.get("passed") else "FAIL"
        lines.append(
            f"**Verification:** `{verification.get('command', '')}` → {mark} "
            f"(exit {verification.get('exit_code')}, {verification.get('duration_seconds')}s)"
        )
        lines.append("")

    dissent = decision.get("dissent") or []
    if dissent:
        lines.append("<details><summary>Dissent</summary>\n")
        for item in dissent[:10]:
            lines.append(f"- {_clip(item, 400)}")
        lines.append("\n</details>\n")

    lines += [
        f"<sub>diff {result.get('diff_chars', 0)} chars"
        f"{' (truncated)' if result.get('diff_truncated') else ''} · "
        f"session `{result.get('session_id', '')}` · generated by Codex-Gravity "
        "(a review gate, not a merge)</sub>",
    ]
    return "\n".join(lines)


def _request(method: str, url: str, token: str, payload: Optional[dict] = None) -> Any:
    data = json.dumps(payload).encode() if payload is not None else None
    request = urllib.request.Request(url, data=data, method=method)
    request.add_header("Authorization", f"Bearer {token}")
    request.add_header("Accept", "application/vnd.github+json")
    request.add_header("X-GitHub-Api-Version", "2022-11-28")
    if data is not None:
        request.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(request, timeout=30) as response:
        body = response.read().decode("utf-8", "replace")
    return json.loads(body) if body.strip() else {}


def upsert_comment(
    repo: str,
    pr: int,
    body: str,
    token: str,
    *,
    api: str = "https://api.github.com",
    request: Callable[..., Any] = _request,
) -> str:
    """Create the sticky comment, or update it when it already exists."""
    if not repo or not pr:
        raise ValueError("repo and pull-request number are required")
    comments = request("GET", f"{api}/repos/{repo}/issues/{pr}/comments?per_page=100", token) or []
    for comment in comments:
        if isinstance(comment, dict) and MARKER in (comment.get("body") or ""):
            request("PATCH", f"{api}/repos/{repo}/issues/comments/{comment['id']}", token, {"body": body})
            return "updated"
    request("POST", f"{api}/repos/{repo}/issues/{pr}/comments", token, {"body": body})
    return "created"


def _pull_request_number() -> Optional[int]:
    explicit = os.environ.get("GITHUB_PR_NUMBER")
    if explicit:
        return int(explicit)
    event_path = os.environ.get("GITHUB_EVENT_PATH")
    if not event_path or not Path(event_path).is_file():
        return None
    try:
        event = json.loads(Path(event_path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    pull_request = event.get("pull_request")
    if isinstance(pull_request, dict) and pull_request.get("number"):
        return int(pull_request["number"])
    if isinstance(event.get("issue"), dict) and event["issue"].get("number"):
        return int(event["issue"]["number"])
    return None


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    path = Path(args[0]) if args else Path("cg-review.json")
    if not path.is_file():
        print(f"action_comment: no review file at {path}", file=sys.stderr)
        return 1
    result = json.loads(path.read_text(encoding="utf-8"))
    if isinstance(result, list):
        result = result[0] if result else {}

    body = build_comment(result)
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN") or ""
    repo = os.environ.get("GITHUB_REPOSITORY", "")
    pr = _pull_request_number()
    api = os.environ.get("GITHUB_API_URL", "https://api.github.com")

    if not token or not repo or not pr:
        missing = [name for name, value in (("GITHUB_TOKEN", token), ("GITHUB_REPOSITORY", repo), ("pull request", pr)) if not value]
        print(f"action_comment: not posting, missing {', '.join(missing)}", file=sys.stderr)
        return 0 if not os.environ.get("GITHUB_ACTIONS") else 1

    try:
        action = upsert_comment(repo, pr, body, token, api=api)
    except (urllib.error.URLError, ValueError, KeyError) as error:
        print(f"action_comment: failed to post the review: {error}", file=sys.stderr)
        return 1
    print(f"action_comment: {action} the review comment on {repo}#{pr}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
